// Auto-migrate — apply pending EF Core migrations in all environments (not just Development).
// __EFMigrationsHistory tracks applied migrations; idempotent across restarts and re-deploys.
var initialMigrationFailed = false;
try
{
    using var scope = app.Services.CreateScope();
    var db = scope.ServiceProvider.GetRequiredService<LiensDbContext>();
    await db.Database.MigrateAsync();
    app.Logger.LogInformation("Liens database migrations applied successfully.");
}
catch (Exception ex)
{
    initialMigrationFailed = true;
    app.Logger.LogWarning(ex, "Could not apply Liens database migrations on startup — schema may be out of sync.");
}

// Repair selling schema drift even when migration history was recorded before
// MySQL finished all non-transactional DDL. Normal startups perform read-only
// checks and skip the guarded recovery operations.
var sellingSchemaRepaired = false;
try
{
    using var scope = app.Services.CreateScope();
    var db = scope.ServiceProvider.GetRequiredService<LiensDbContext>();
    sellingSchemaRepaired = await Liens.Infrastructure.Persistence.Migrations.SellingSchemaRepair.EnsureAsync(db, app.Logger);
}
catch (Exception ex)
{
    app.Logger.LogWarning(ex, "Selling schema recovery could not complete — selling APIs may be unavailable.");
}

// Replay the guarded legacy update-event DDL independently of migration
// history. This repairs deployments where MySQL completed only part of the
// non-transactional migration or an earlier pending migration blocked it.
var legacyUpdateEventMigrationWasPending = false;
var legacyUpdateEventSchemaRecoveryRequired = false;
try
{
    using var scope = app.Services.CreateScope();
    var db = scope.ServiceProvider.GetRequiredService<LiensDbContext>();
    legacyUpdateEventSchemaRecoveryRequired = db.Database.IsRelational();
    if (legacyUpdateEventSchemaRecoveryRequired)
    {
        legacyUpdateEventMigrationWasPending =
            await Liens.Infrastructure.Persistence.Migrations.LegacyUpdateEventSchemaRepair.EnsureAsync(
                db,
                app.Logger);
    }
}
catch (Exception ex)
{
    if (legacyUpdateHistoryEnabled && legacyUpdateEventSchemaRecoveryRequired)
    {
        app.Logger.LogCritical(
            ex,
            "Legacy update-event schema recovery failed while imported history reads are enabled.");
        throw;
    }

    app.Logger.LogWarning(
        ex,
        "Legacy update-event schema recovery could not complete — imported history remains unavailable.");
}

// A partially applied MySQL migration can block the first migration pass. Once
// guarded schema recovery repairs that state, retry so EF can record the repaired
// migration and continue to later migrations such as AddAutoGeneratedReports.
if (initialMigrationFailed || sellingSchemaRepaired || legacyUpdateEventMigrationWasPending)
{
    try
    {
        using var scope = app.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<LiensDbContext>();
        await db.Database.MigrateAsync();
        app.Logger.LogInformation("Liens database migrations applied successfully after schema recovery.");
    }
    catch (Exception ex)
    {
        app.Logger.LogWarning(
            ex,
            "Could not apply Liens database migrations after schema recovery — schema may still be out of sync.");
    }
}

// Replay the guarded auto-generated-report DDL independently of migration
// history. This also repairs environments where history was recorded after
// only part of MySQL's non-transactional DDL completed.
try
{
    using var scope = app.Services.CreateScope();
    var db = scope.ServiceProvider.GetRequiredService<LiensDbContext>();
    await Liens.Infrastructure.Persistence.Migrations.AutoGeneratedReportSchemaRepair.EnsureAsync(
        db,
        app.Logger);
}
catch (Exception ex)
