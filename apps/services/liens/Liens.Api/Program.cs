// ── EnsureLiensSchemaTablesAsync ─────────────────────────────────────────
// Idempotently creates tables that are defined in EF migrations but may not
// have been applied to the live DB (production schema-drift guard).
static async Task EnsureLiensSchemaTablesAsync(LiensDbContext db, ILogger logger)
{
    var conn = db.Database.GetDbConnection();
    if (conn.State != System.Data.ConnectionState.Open)
        await conn.OpenAsync();

    // liens_WorkflowTransitions — added by migration 20260418200000
    const string createWorkflowTransitions = """
        CREATE TABLE IF NOT EXISTS `liens_WorkflowTransitions` (
            `Id`               char(36)    NOT NULL COLLATE ascii_general_ci,
            `WorkflowConfigId` char(36)    NOT NULL COLLATE ascii_general_ci,
            `FromStageId`      char(36)    NOT NULL COLLATE ascii_general_ci,
            `ToStageId`        char(36)    NOT NULL COLLATE ascii_general_ci,
            `IsActive`         tinyint(1)  NOT NULL,
            `SortOrder`        int         NOT NULL,
            `CreatedByUserId`  char(36)    NOT NULL COLLATE ascii_general_ci,
            `UpdatedByUserId`  char(36)    NULL     COLLATE ascii_general_ci,
            `CreatedAtUtc`     datetime(6) NOT NULL,
            `UpdatedAtUtc`     datetime(6) NOT NULL,
            PRIMARY KEY (`Id`),
            CONSTRAINT `FK_lWT_WorkflowConfigId`
                FOREIGN KEY (`WorkflowConfigId`) REFERENCES `liens_WorkflowConfigs` (`Id`) ON DELETE CASCADE,
            CONSTRAINT `FK_lWT_FromStageId`
                FOREIGN KEY (`FromStageId`) REFERENCES `liens_WorkflowStages` (`Id`) ON DELETE RESTRICT,
            CONSTRAINT `FK_lWT_ToStageId`
                FOREIGN KEY (`ToStageId`) REFERENCES `liens_WorkflowStages` (`Id`) ON DELETE RESTRICT
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
        """;

    // TASK-MIG-09: liens_TaskGovernanceSettings removed — table dropped by migration 20260421000002.
    // TASK-MIG-09: liens_TaskTemplates removed — table dropped by migration 20260421000002.

    using var cmd = conn.CreateCommand();
    cmd.CommandText = createWorkflowTransitions;
    await cmd.ExecuteNonQueryAsync();
    logger.LogInformation("EnsureLiensSchemaTablesAsync: liens_WorkflowTransitions ensured.");

    // LS-LIENS-FLOW-007 — liens_Tasks.WorkflowInstanceId + WorkflowStepKey columns
    // Added by migration 20260420000002_AddTaskFlowLinkage. MySQL does not support
    // ADD COLUMN IF NOT EXISTS, so we guard via information_schema.
    cmd.CommandText = """
        SELECT COUNT(*) FROM information_schema.COLUMNS
        WHERE TABLE_SCHEMA = DATABASE()
          AND TABLE_NAME   = 'liens_Tasks'
          AND COLUMN_NAME  = 'WorkflowInstanceId'
        """;
    var hasWorkflowInstanceId = Convert.ToInt64(await cmd.ExecuteScalarAsync()) > 0;

    if (!hasWorkflowInstanceId)
    {
        cmd.CommandText = """
            ALTER TABLE `liens_Tasks`
                ADD COLUMN `WorkflowInstanceId` char(36)     NULL COLLATE ascii_general_ci,
                ADD COLUMN `WorkflowStepKey`    varchar(200) NULL
            """;
        await cmd.ExecuteNonQueryAsync();
        logger.LogInformation("EnsureLiensSchemaTablesAsync: Added WorkflowInstanceId/WorkflowStepKey to liens_Tasks.");

        try
        {
            cmd.CommandText = "CREATE INDEX `IX_Tasks_TenantId_WorkflowInstanceId` ON `liens_Tasks` (`TenantId`, `WorkflowInstanceId`)";
            await cmd.ExecuteNonQueryAsync();
            logger.LogInformation("EnsureLiensSchemaTablesAsync: Created IX_Tasks_TenantId_WorkflowInstanceId.");
        }
        catch (Exception idxEx)
        {
            logger.LogWarning(idxEx, "EnsureLiensSchemaTablesAsync: Could not create IX_Tasks_TenantId_WorkflowInstanceId (may already exist).");
        }
    }
    else
    {
        logger.LogInformation("EnsureLiensSchemaTablesAsync: liens_Tasks flow-linkage columns already present.");
    }

    // LS-LIENS-CONTACT-DRIFT — ensure contact subtype linkage columns exist even
    // when startup migrations were skipped or partially failed. Without these
    // columns, simple list reads can fail with MySQL "Unknown column" errors.
    async Task<bool> HasContactColumnAsync(string columnName)
    {
        cmd.CommandText = $"""
            SELECT COUNT(*) FROM information_schema.COLUMNS
            WHERE TABLE_SCHEMA = DATABASE()
              AND TABLE_NAME   = 'liens_Contacts'
              AND COLUMN_NAME  = '{columnName}'
            """;
        return Convert.ToInt64(await cmd.ExecuteScalarAsync()) > 0;
    }

    if (!await HasContactColumnAsync("ContactSubtype"))
    {
        cmd.CommandText = """
            ALTER TABLE `liens_Contacts`
                ADD COLUMN `ContactSubtype` varchar(50) NULL
            """;
        await cmd.ExecuteNonQueryAsync();
        logger.LogInformation("EnsureLiensSchemaTablesAsync: Added ContactSubtype to liens_Contacts.");
    }

    if (!await HasContactColumnAsync("FacilityId"))
    {
        cmd.CommandText = """
            ALTER TABLE `liens_Contacts`
                ADD COLUMN `FacilityId` char(36) NULL COLLATE ascii_general_ci
            """;
        await cmd.ExecuteNonQueryAsync();
        logger.LogInformation("EnsureLiensSchemaTablesAsync: Added FacilityId to liens_Contacts.");
    }

    if (!await HasContactColumnAsync("LawFirmId"))
    {
        cmd.CommandText = """
            ALTER TABLE `liens_Contacts`
                ADD COLUMN `LawFirmId` char(36) NULL COLLATE ascii_general_ci
            """;
        await cmd.ExecuteNonQueryAsync();
        logger.LogInformation("EnsureLiensSchemaTablesAsync: Added LawFirmId to liens_Contacts.");
    }

    async Task<bool> HasContactIndexAsync(string indexName)
    {
        cmd.CommandText = $"""
            SELECT COUNT(*) FROM information_schema.STATISTICS
            WHERE TABLE_SCHEMA = DATABASE()
              AND TABLE_NAME   = 'liens_Contacts'
              AND INDEX_NAME   = '{indexName}'
            """;
        return Convert.ToInt64(await cmd.ExecuteScalarAsync()) > 0;
    }

    if (!await HasContactIndexAsync("IX_Contacts_TenantId_FacilityId_ContactSubtype"))
    {
        cmd.CommandText = """
            CREATE INDEX `IX_Contacts_TenantId_FacilityId_ContactSubtype`
            ON `liens_Contacts` (`TenantId`, `FacilityId`, `ContactSubtype`)
            """;
        await cmd.ExecuteNonQueryAsync();
        logger.LogInformation("EnsureLiensSchemaTablesAsync: Created IX_Contacts_TenantId_FacilityId_ContactSubtype.");
    }

    if (!await HasContactIndexAsync("IX_Contacts_TenantId_LawFirmId_ContactSubtype"))
    {
        cmd.CommandText = """
            CREATE INDEX `IX_Contacts_TenantId_LawFirmId_ContactSubtype`
            ON `liens_Contacts` (`TenantId`, `LawFirmId`, `ContactSubtype`)
            """;
        await cmd.ExecuteNonQueryAsync();
        logger.LogInformation("EnsureLiensSchemaTablesAsync: Created IX_Contacts_TenantId_LawFirmId_ContactSubtype.");
    }

    // LS-LIENS-LIEN-DRIFT — ensure legacy medical fields exist for dashboard
    // exports against older dumps that predate migration 20260625000001.
    async Task<bool> HasLienColumnAsync(string columnName)
    {
        cmd.CommandText = $"""
            SELECT COUNT(*) FROM information_schema.COLUMNS
            WHERE TABLE_SCHEMA = DATABASE()
              AND TABLE_NAME   = 'liens_Liens'
              AND COLUMN_NAME  = '{columnName}'
            """;
        return Convert.ToInt64(await cmd.ExecuteScalarAsync()) > 0;
    }

    if (!await HasLienColumnAsync("InitialServiceDate"))
    {
        cmd.CommandText = """
            ALTER TABLE `liens_Liens`
                ADD COLUMN `InitialServiceDate` date NULL
            """;
        await cmd.ExecuteNonQueryAsync();
        logger.LogInformation("EnsureLiensSchemaTablesAsync: Added InitialServiceDate to liens_Liens.");
    }

    if (!await HasLienColumnAsync("EndServiceDate"))
    {
        cmd.CommandText = """
            ALTER TABLE `liens_Liens`
                ADD COLUMN `EndServiceDate` date NULL
            """;
        await cmd.ExecuteNonQueryAsync();
        logger.LogInformation("EnsureLiensSchemaTablesAsync: Added EndServiceDate to liens_Liens.");
    }

    if (!await HasLienColumnAsync("IsBulk"))
    {
        cmd.CommandText = """
            ALTER TABLE `liens_Liens`
                ADD COLUMN `IsBulk` varchar(10) NULL
            """;
        await cmd.ExecuteNonQueryAsync();
        logger.LogInformation("EnsureLiensSchemaTablesAsync: Added IsBulk to liens_Liens.");
    }

    if (!await HasLienColumnAsync("IsServicing"))
    {
        cmd.CommandText = """
            ALTER TABLE `liens_Liens`
                ADD COLUMN `IsServicing` varchar(10) NULL
            """;
        await cmd.ExecuteNonQueryAsync();
        logger.LogInformation("EnsureLiensSchemaTablesAsync: Added IsServicing to liens_Liens.");
    }

    // LS-LIENS-OFFER-DRIFT — liens_LienOffers.SubmittedByPlatformUserId added by
    // migration 20260906010000_AddSellingNotificationInboxOutbox. When that
    // migration was skipped or only partially applied, every query that
    // materializes a LienOffer (e.g. the selling lien detail endpoint) fails with
    // a MySQL "Unknown column" error and returns 500 for all lien IDs.
    cmd.CommandText = """
        SELECT COUNT(*) FROM information_schema.COLUMNS
        WHERE TABLE_SCHEMA = DATABASE()
          AND TABLE_NAME   = 'liens_LienOffers'
          AND COLUMN_NAME  = 'SubmittedByPlatformUserId'
        """;
    if (Convert.ToInt64(await cmd.ExecuteScalarAsync()) == 0)
    {
        cmd.CommandText = """
            ALTER TABLE `liens_LienOffers`
                ADD COLUMN `SubmittedByPlatformUserId` char(36) NULL COLLATE ascii_general_ci
            """;
        await cmd.ExecuteNonQueryAsync();
        logger.LogInformation("EnsureLiensSchemaTablesAsync: Added SubmittedByPlatformUserId to liens_LienOffers.");
    }
}
